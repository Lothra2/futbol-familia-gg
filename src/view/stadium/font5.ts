const MAP: Record<string, string> = { Á: 'A', É: 'E', Í: 'I', Ó: 'O', Ú: 'U', Ñ: 'N', Ü: 'U' };

/** Width in pixels of a text at scale `s` (6 columns per letter: 5 plus one of space). */
export const textWidth = (txt: string, s = 1): number => txt.length * 6 * s;

/** Draws `txt` with the top-left corner at (x, y). `colour(i)` gives the colour of the i-th letter. */
export function drawText(c: CanvasRenderingContext2D, txt: string, x: number, y: number, s: number, colour: (i: number) => string): void {
  [...txt.toUpperCase()].forEach((ch, i) => {
    const g = G[MAP[ch] ?? ch] ?? G['?'];
    c.fillStyle = colour(i);
    g.forEach((row, ry) => [...row].forEach((p, rx) => { if (p === '#') c.fillRect(x + (i * 6 + rx) * s, y + ry * s, s, s); }));
    if (ch === 'Á' || ch === 'É' || ch === 'Í' || ch === 'Ó' || ch === 'Ú') c.fillRect(x + (i * 6 + 3) * s, y - s, s, s);
  });
}
