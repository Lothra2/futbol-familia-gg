// After `vite build`: writes dist/sw.js, the service worker that keeps the whole game in the device so it plays with no connection
// (on a plane). The list of files and the version of this build are written into it, so every deploy is a new worker that fetches the new
// files and throws the old ones away.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
const dist = 'dist', files = [];
const walk = (d) => { for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p); else files.push(relative(dist, p).split('\\').join('/')); } };
walk(dist);
const keep = files.filter((f) => f !== 'sw.js' && !f.endsWith('.map') && !f.startsWith('_'));
const v = Date.now().toString(36);
writeFileSync(join(dist, 'sw.js'), `// generated by tools/precache.mjs
const V = 'ffgg-${v}', FILES = ${JSON.stringify(['./', ...keep.map((f) => './' + f)])};
self.addEventListener('install', (e) => {
  // one file at a time, a few together: a file that fails does not stop the others
  e.waitUntil(caches.open(V).then(async (c) => {
    for (let i = 0; i < FILES.length; i += 8) await Promise.all(FILES.slice(i, i + 8).map((u) => c.add(new Request(u, { cache: 'reload' })).catch(() => {})));
    await self.skipWaiting();
  }));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('ffgg-') && k !== V).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const r = e.request, u = new URL(r.url);
  if (r.method !== 'GET' || u.origin !== location.origin) return;
  // the page itself: the network first (a new version arrives at once), what is kept if there is no connection
  if (r.mode === 'navigate') { e.respondWith(fetch(r).then((x) => { const y = x.clone(); caches.open(V).then((c) => c.put('./', y)); return x; }).catch(() => caches.match('./', { ignoreSearch: true, ignoreVary: true }))); return; }
  // everything else: what is kept (whatever its ?v=), else the network, and keep it
  e.respondWith(caches.match(r, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit ?? fetch(r).then((x) => { if (x.ok) { const y = x.clone(); caches.open(V).then((c) => c.put(r, y)); } return x; })));
});
`);
console.log(`sw.js: ${keep.length} archivos, versión ${v}`);
